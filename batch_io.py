"""Stream ZIP members to disk; never materialize expanded batch contents in RAM."""
from dataclasses import dataclass
from pathlib import PurePosixPath
import shutil
import zipfile

MAX_MEMBER_BYTES = 200 * 1024 * 1024

def supported(info):
    path=PurePosixPath(info.filename)
    return (not info.is_dir() and '__MACOSX' not in path.parts and not path.name.startswith('._')
            and path.suffix.lower() in ('.log','.sdf'))

def inventory(uploads):
    total=0; needs_obabel=False
    for upload in uploads:
        if PurePosixPath(upload.name).suffix.lower()=='.zip':
            with zipfile.ZipFile(upload) as archive:
                members=[i for i in archive.infolist() if supported(i)]
                if not members: raise ValueError(f'{upload.name}: no .log or .sdf files found in ZIP')
                for info in members:
                    if info.flag_bits & 1: raise ValueError(f'{upload.name}: encrypted ZIP members are not supported')
                    if info.file_size>MAX_MEMBER_BYTES: raise ValueError(f'{info.filename}: expanded file exceeds 200 MB; split the input file')
                total+=len(members)
                needs_obabel |= any(PurePosixPath(i.filename).suffix.lower()=='.log' for i in members)
        else:
            total+=1; needs_obabel |= PurePosixPath(upload.name).suffix.lower()=='.log'
    return total,needs_obabel

@dataclass
class ZipMember:
    name: str
    archive: zipfile.ZipFile
    info: zipfile.ZipInfo

    def save_to(self,path):
        # The destination is generated by the app, never taken from an archive path.
        with self.archive.open(self.info) as source, path.open('wb') as target:
            shutil.copyfileobj(source,target,length=1024*1024)

def iter_inputs(uploads):
    for upload in uploads:
        if PurePosixPath(upload.name).suffix.lower()=='.zip':
            with zipfile.ZipFile(upload) as archive:
                for info in archive.infolist():
                    if supported(info):
                        yield ZipMember(f'{upload.name}/{info.filename}',archive,info)
        else:
            yield upload
